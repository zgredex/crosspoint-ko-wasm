function withCString(str, fn) {
  const bytes = new TextEncoder().encode(str == null ? '' : String(str));
  const ptr = api._malloc(bytes.length + 1);
  try {
    api.HEAPU8.set(bytes, ptr);
    api.HEAPU8[ptr + bytes.length] = 0;
    return fn(ptr);
  } finally {
    api._free(ptr);
  }
}

// ---- progressive section build -------------------------------------------------
// A spine is laid out one page at a time until the first page exists, then extended in chunks while
// the reader looks at it. Measured on a 326-page single spine: 48.8 ms of a 68.2 ms first page was
// section layout, so this is the difference between "wait for the chapter" and "wait for one page".
const FIRST_PAGES = 1;      // enough for the requested page to exist
const BUILD_CHUNK = 4;      // pages per continuation tick
let sectionGen = 0;         // bumped by anything that replaces the live section
let sectionEstimates = {};

// Anything that mutates the engine's live section must bump this, or a continuation would keep laying
// out a section nobody is looking at (and could interleave with an export's own buildSection).
function invalidateSection() { sectionGen += 1; }


async function continueSection(spine, gen, chunk) {
  while (gen === sectionGen && currentSpine === spine && !foregroundExportRunning && !warmRunning) {
    if (api._ko_spine_build_complete() === 1) break;
    const t0 = performance.now();
    const n = api._ko_build_spine_more(chunk);
    if (n < 0) break;
    currentPages = api._ko_spine_pages_available();
    const est = api._ko_spine_pages_estimated();
    const done = api._ko_spine_build_complete() === 1;
    sectionEstimates[spine] = { pages: currentPages, estimated: est, complete: done };
    // Progress carries no id: the page updates its "x / y" total without a round trip.
    self.postMessage({ sectionProgress: true, spine, pages: currentPages, estimated: est,
                       complete: done, ms: +(performance.now() - t0).toFixed(2) });
    if (done) break;
    await yieldToLoop();          // let render / navigation / settings messages run between chunks
  }
  if (gen === sectionGen && currentSpine === spine && api._ko_spine_build_complete() === 1) {
    sectionEstimates[spine] = { pages: currentPages, estimated: currentPages, complete: true };
    self.postMessage({ sectionProgress: true, spine, pages: currentPages, estimated: currentPages,
                       complete: true, ms: 0 });
  }
}

// `early` = {promise, startedAt} for a read the caller started BEFORE awaiting initPromise. The read needs
// no engine, so on a cold page load the module's fetch/compile and the file read overlap instead of
// running back to back. Everything below is otherwise unchanged, including the ownership contract.
async function loadEngineBook(data, timing, early) {
  const t0 = performance.now();
  if (data.epub) {
    const bytes = new Uint8Array(data.epub);
    const tCopy = performance.now();
    const ptr = api._malloc(bytes.length);
    api.HEAPU8.set(bytes, ptr);
    timing.wasmCopyMs = performance.now() - tCopy;
    timing.path = 'copy(ArrayBuffer)';
    const t = performance.now();
    const n = api._ko_load_epub(ptr, bytes.length, '/book.epub');
    timing.engineLoadMs = performance.now() - t;
    api._free(ptr);                       // ko_load_epub copies; this buffer stays ours
    timing.totalLoadMs = performance.now() - t0;
    return n;
  }
  const blob = data.blob;

  if (data.streamEpub && blob && blob.stream && api._ko_epub_alloc && api._ko_load_epub_owned) {
    const size = blob.size;
    const ptr = api._ko_epub_alloc(size);
    if (ptr) {
      let off = 0, overflow = false;
      const tStream = performance.now();
      const reader = blob.stream().getReader();
      for (;;) {
        const { value, done } = await reader.read();
        if (done) break;
        if (off + value.byteLength > size) { overflow = true; break; }
        api.HEAPU8.set(value, ptr + off);
        off += value.byteLength;
      }
      timing.streamMs = performance.now() - tStream;
      if (!overflow && off === size) {
        timing.path = 'stream+own';
        const t = performance.now();
        const n = api._ko_load_epub_owned(ptr, size, '/book.epub');
        timing.engineLoadMs = performance.now() - t;
        timing.totalLoadMs = performance.now() - t0;
        return n;   // ownership went with the call, in both outcomes
      }
      api._free(ptr);                     // streaming failed: the buffer is still ours
      timing.streamFallback = true;
    }
  }

  // The read and the heap allocation are independent, so start the read first and allocate while it is
  // in flight. `wasmAllocMs` and `wasmMemcpyMs` are separate because they have different fixes: growth
  // can overlap I/O, a memcpy cannot.
  let readPromise;
  let readStartedAt;
  if (early && early.promise) {
    readPromise = early.promise;
    readStartedAt = early.startedAt;           // may be before initPromise resolved
  } else {
    readStartedAt = performance.now();
    readPromise = blob.arrayBuffer();
  }
  const tAlloc = performance.now();
  const ptr = api._ko_epub_alloc ? api._ko_epub_alloc(blob.size) : api._malloc(blob.size);
  timing.wasmAllocMs = performance.now() - tAlloc;
  if (!ptr) {
    await readPromise.catch(() => {});
    throw new Error('EPUB allocation failed');
  }
  const tWait = performance.now();
  const buf = await readPromise;
  const waitedFor = performance.now() - tWait;
  const readDone = performance.now();
  const bytes = new Uint8Array(buf);
  const tCopy = performance.now();
  api.HEAPU8.set(bytes, ptr);
  timing.wasmMemcpyMs = performance.now() - tCopy;
  // Read wall time from when it STARTED (possibly before init) plus the part still outstanding once the
  // engine was ready; the difference is what the overlap actually bought.
  timing.blobReadMs = +(readDone - readStartedAt).toFixed(2);
  timing.blobWaitAfterInitMs = +waitedFor.toFixed(2);
  timing.blobBootOverlapMs = +Math.max(0, timing.blobReadMs - waitedFor).toFixed(2);
  timing.wasmCopyMs = timing.wasmMemcpyMs;
  if (api._ko_load_epub_owned) {
    // Adopt: storage takes this buffer, so the book is not copied again in C++.
    //
    // OWNERSHIP IS CONSUMED BY THE CALL, SUCCESS OR FAILURE. There is deliberately no fallback to
    // ko_load_epub after this: the driver mounts the blob before it parses, so a failed parse has
    // already dropped it — which frees this pointer. Re-entering the copying path would read from
    // transferred memory, and the api._free() that path ends with would be a double free. A parse
    // failure is also not something a copy would fix: the same bytes would fail identically.
    timing.path = 'read+adopt';
    const t = performance.now();
    const n = api._ko_load_epub_owned(ptr, bytes.length, '/book.epub');
    timing.engineLoadMs = performance.now() - t;
    timing.totalLoadMs = performance.now() - t0;
    return n;
  }
  // The copying path exists only for a module whose API predates ko_load_epub_owned: here the buffer
  // was never handed over, so it is still ours to free.
  timing.path = 'copy(Blob)';
  const t = performance.now();
  const n = api._ko_load_epub(ptr, bytes.length, '/book.epub');
  timing.engineLoadMs = performance.now() - t;
  api._free(ptr);
  timing.totalLoadMs = performance.now() - t0;
  return n;
}

self.onmessage = async (ev) => {
  const { id, cmd } = ev.data;
  let earlyRead = null;
  const t0Open = performance.now();
  try {
    // Start the file read BEFORE waiting for the engine. Reading a File/Blob needs no WASM, and on a cold
    // page load this is the one place where the two unavoidable startup costs can overlap. The streaming
    // path manages its own read and the ArrayBuffer path has nothing to read, so both are excluded.
    //
    // `noEarlyRead` is the CONTROL for measuring it: the same build, the same book, one variable — the
    // read either starts before `await initPromise` or after it, exactly as it did before this change.
    if ((cmd === 'load' || cmd === 'openPreview') && ev.data.blob && !ev.data.streamEpub
        && !ev.data.noEarlyRead && typeof ev.data.blob.arrayBuffer === 'function') {
      const promise = ev.data.blob.arrayBuffer();
      promise.catch(() => {});            // init may fail first; do not surface an unhandled rejection
      earlyRead = { promise, startedAt: performance.now() };
    }
    const tInit0 = performance.now();
    await initPromise;   // engine ready before any command
    const initWaitMs = performance.now() - tInit0;
    switch (cmd) {      case 'ping': {
        const vp = api._ko_version();
        const ver = api.UTF8ToString ? api.UTF8ToString(vp) : String(vp);
        post(id, true, { version: ver });
        break;
      }

      // Cold-boot phases, plus the browser's own accounting of the engine fetch. The resource
      // entry answers the question the phase numbers cannot: whether the time went into the
      // network or into compilation/instantiation. `encodedBodySize` is what crossed the wire,
      // `decodedBodySize` what had to be compiled.
      case 'bootstats': {
        const boot = self.__koBoot || {};
        let resource = null;
        if (typeof performance !== 'undefined' && performance.getEntriesByType) {
          // Match the WASM specifically: 'ko_xtch_wasm.' also matches the 19 KB glue, which is how
          // the first version of this reported a 19 KB engine fetch as the engine's own transfer.
          const e = performance.getEntriesByType('resource')
            .find((x) => x.name && /ko_xtch_wasm\.[a-f0-9]+\.wasm|ko_xtch_wasm\.wasm/.test(x.name));
          if (e) {
            resource = {
              encodedBodySize: e.encodedBodySize,
              decodedBodySize: e.decodedBodySize,
              transferSize: e.transferSize,
              downloadMs: +(e.responseEnd - e.responseStart).toFixed(1),
            };
          }
        }
        post(id, true, { phases: boot.phases || null, workerStart: boot.workerStart || 0,
                         engineReadyWall: boot.engineReadyWall || 0, resource,
                         embedded: embeddedFaces(), lazyFaces: boot.lazyFaces || [],
                         facesRegistered: boot.facesRegistered || [], faceError: boot.faceError || null });
        break;
      }

      case 'load': {
        if (foregroundExportRunning) { post(id, false, { error: 'book locked during export' }); break; }
        if (!api) await init();
        // §2: stop the warm and WAIT for it before the engine's EPUB is replaced. Bumping the token
        // alone only asks it to abort at its next spine yield, and the suspended warm handler would
        // then resume its spine loop against the NEW book.
        await stopWarmBeforeMutation();
        // EITHER an ArrayBuffer or a Blob. A Blob matters now that two engines exist: an ArrayBuffer
        // handed to one worker is DETACHED by the transfer, so the second engine could never read it,
        // and keeping a second copy in the page would double the book's memory for a 200 MB book.
        // Each worker reads the same Blob instead.
        dropWarmResult();     // §3: warm bytes belong to the previous book
        invalidateSection();
        loadTiming = { initWaitMs: +initWaitMs.toFixed(2) };
        spineCount = await loadEngineBook(ev.data, loadTiming, earlyRead);
        loadTiming.bookBytes = ev.data.epub ? ev.data.epub.byteLength : (ev.data.blob ? ev.data.blob.size : 0);
        loadTiming.heapAfterLoadBytes = api.HEAPU8.buffer.byteLength;
        if (spineCount < 0) {
          post(id, false, { error: 'Epub::load failed' });
          return;
        }
        // title
        const tbuf = api._malloc(512);
        api._ko_get_title(tbuf, 512);
        const title = api.UTF8ToString(tbuf);
        api._free(tbuf);
        currentSpine = -1;
        currentPages = 0;
        bookGen += 1;                // §5: new book, new frame namespace
        clearFrameCache();
        appliedFont = null;          // §1: a load resets the engine's font state, so force a re-apply
        // a new book cleared the in-memory FS: re-apply the custom font if one
        // is loaded, so the reader face survives chapter navigation
        if (customFontBytes && currentSpec && currentSpec.font === 'custom') {
          // a new book cleared the in-memory FS, so the custom font has to go back in; if that fails
          // the engine would render this book with the default face while the page believes otherwise
          if (!applyFont('custom')) {
            const ep = api._ko_error();
            post(id, false, { error: 'epdfont re-apply after book load failed: ' +
                                     (api.UTF8ToString(ep) || 'failed') });
            return;
          }
        }
        // totalLoadMs is set by loadEngineBook (it owns the whole sequence, including the font re-apply
        // deadline above it); nothing to add here.
        // Spine labels are NOT sent here: one label per spine in front of the first page buys nothing,
        // and an omnibus has thousands. The page asks for them in batches once the first frame is up.
        // Where the reference reader would open: its own text reference, not always spine 0. The page
        // starts there; the container still holds every spine.
        const startSpine = api._ko_text_reference_spine ? api._ko_text_reference_spine() : 0;
        post(id, true, { spineCount, title, startSpine, timing: loadTiming });
        break;
      }

      case 'spec': {
        if (foregroundExportRunning) { post(id, false, { error: 'settings locked during export' }); break; }
        // §3 of the 1.4 audit: the worker owns this invariant, not the caller. window.__call is
        // exposed for debugging, so a raw spec during a warm must not change g_spec between spines.
        await stopWarmBeforeMutation();
        tick('spec');
        // margins: viewable area + screenMargin on all four sides (no UI reserve)
        await applySpec(ev.data.spec);
        const vp = viewportInfo(currentSpec);
        tock('spec');
        post(id, true, {
          specKey: layoutKey(currentSpec),          // layout key: the only thing that repaginates
          renderKey: renderKey(currentSpec),
          layoutChanged: true,
          margins: vp.margins,
          viewport: vp.viewport,
        });
        break;
      }

      case 'build': {
        tick('build');
        const n = api._ko_build_spine(ev.data.spine);
        tock('build');
        if (n < 0) {
          const ep = api._ko_error();
          const msg = api.UTF8ToString(ep) || 'build failed';
          post(id, false, { error: 'build failed: ' + msg });
          return;
        }
        currentSpine = ev.data.spine;
        currentPages = n;
        post(id, true, { pages: n });
        break;
      }

      // P3: open + first page in ONE round trip. First open otherwise costs
      //   page->worker load, worker->page metadata, page UI work, page->worker render, worker->page frame
      // and nothing about the first page needs that middle hop. `load` is kept for export/pool workers,
      // which want metadata without a preview frame.
      case 'openPreview': {
        if (foregroundExportRunning) { post(id, false, { error: 'book locked during export' }); break; }
        if (!api) await init();
        await stopWarmBeforeMutation();
        dropWarmResult();
        invalidateSection();
        loadTiming = { initWaitMs: +initWaitMs.toFixed(2) };
        spineCount = await loadEngineBook(ev.data, loadTiming, earlyRead);
        loadTiming.bookBytes = ev.data.epub ? ev.data.epub.byteLength
                                            : (ev.data.blob ? ev.data.blob.size : 0);
        loadTiming.heapAfterLoadBytes = api.HEAPU8.buffer.byteLength;
        if (spineCount < 0) {
          post(id, false, { error: 'Epub::load failed', timing: loadTiming });
          return;
        }
        const titleBuf = api._malloc(512);
        api._ko_get_title(titleBuf, 512);
        const openTitle = api.UTF8ToString(titleBuf);
        api._free(titleBuf);
        bookGen += 1;
        currentSpine = -1;
        currentPages = 0;
        if (ev.data.spec) await applySpec(ev.data.spec);
        const startSpine = api._ko_text_reference_spine ? api._ko_text_reference_spine() : 0;
        const tBuild0 = performance.now();
        const pages = api._ko_start_spine(startSpine, FIRST_PAGES);
        if (pages < 0) {
          post(id, false, { error: 'build failed: ' + (api.UTF8ToString(api._ko_error()) || 'unknown'),
                            timing: loadTiming });
          return;
        }
        currentSpine = startSpine;
        currentPages = pages;
        builtKey = layoutKey(currentSpec || {});
        builtFontStamp = fontStamp;
        const buildMs = performance.now() - tBuild0;
        const wantMono = ev.data.mode === 0;
        const tRender0 = performance.now();
        const rc = renderPageEngine(0, wantMono);
        if (rc !== 0) {
          post(id, false, { error: 'first page render failed', timing: loadTiming });
          return;
        }
        const renderMs = performance.now() - tRender0;
        const tCompose0 = performance.now();
        const frame = wantMono ? composeMono() : composePage();
        const composeMs = performance.now() - tCompose0;
        const gen = sectionGen;
        const tx = frame.data.buffer;
        post(id, true, {
          title: openTitle,
          spineCount,
          startSpine,
          page: 0,
          pages,
          total: Math.max(pages, api._ko_spine_pages_estimated ? api._ko_spine_pages_estimated() : pages),
          image: tx,
          mono: wantMono,
          cached: false,
          timing: Object.assign({}, loadTiming,
                                renderTiming(tRender0, buildMs, renderMs, composeMs, false, readImagePerf()),
                                { totalOpenWorkerMs: +(performance.now() - t0Open).toFixed(2) }),
        }, [tx]);
        // The rest of the spine keeps building behind the drawn frame.
        continueSection(startSpine, gen, BUILD_CHUNK);
        break;
      }

      case 'render': {
        // §2/§8: the spec travels with the render, so an ordinary page turn is one request and a
        // settings change is one request too. When it has not changed, this does nothing at all.
        let vpInfo = null;
        if (ev.data.spec) {
          const incomingSpec = Object.assign(defaultSpec(), ev.data.spec);
          const changesSpec = renderKey(incomingSpec) !== renderKey(currentSpec || {});
          // §1: a render carrying a CHANGED spec mutates engine state, so it is refused during a
          // foreground export. Navigation with an unchanged (or absent) spec stays fully allowed.
          if (changesSpec && foregroundExportRunning) {
            post(id, false, { error: 'settings locked during export' });
            break;
          }
          // §3: and it must not change g_spec underneath a running warm either
          if (changesSpec) await stopWarmBeforeMutation();
          if (await applySpecIfChanged(ev.data.spec)) vpInfo = viewportInfo(currentSpec);
        }
        const tRender0 = performance.now();
        const key = layoutKey(currentSpec || {});
        const wantMono = ev.data.mode === 0;   // 1-bit XTC preview (BW plane only)
        // rebuild if spine, LAYOUT, OR loaded font changed since the last build
        // (a custom-font swap changes glyphs/metrics but not the worker spec;
        //  pixel-only options like AA/dither/tone depth must not repaginate — §3)
        let continuation = null;
        if (ev.data.spine !== currentSpine || key !== builtKey ||
            fontStamp !== builtFontStamp) {
          COUNTERS.builds += 1;
          tick('rebuild');
          let n;
          if (ev.data.progressive === false) {
            n = api._ko_build_spine(ev.data.spine);       // one-shot (the gate's reference path)
          } else {
            invalidateSection();
            const gen = sectionGen;
            n = api._ko_start_spine(ev.data.spine, FIRST_PAGES);
            if (n >= 0) continuation = { spine: ev.data.spine, gen };
          }
          tock('rebuild');
          if (n < 0) {
            const ep = api._ko_error();
            const msg = api.UTF8ToString(ep) || 'build failed';
            post(id, false, { error: 'build failed: ' + msg });
            return;
          }
          currentSpine = ev.data.spine;
          currentPages = n;
          builtKey = key;
          builtFontStamp = fontStamp;
          sectionEstimates[ev.data.spine] = {
            pages: n,
            estimated: api._ko_spine_pages_estimated(),
            complete: api._ko_spine_build_complete() === 1,
          };
        }
        const buildMs = performance.now() - tRender0;
        let page = ev.data.page;
        if (page < 0) page = 0;
        if (page >= currentPages) page = currentPages - 1;
        // Repeat navigation: the composed frame is a pure function of these five inputs, and
        // the cached copy is already out of wasm memory.
        const rk = renderKey(currentSpec || {});
        const frameKey = bookGen + ':' + currentSpine + ':' + page + ':' + (wantMono ? 1 : 0) + ':' + rk + ':' + builtFontStamp;
        const cachedFrame = frameCacheGet(frameKey);
        if (cachedFrame) {
          COUNTERS.cacheHits += 1;
          const reply = new Uint8ClampedArray(cachedFrame.data.length);
          reply.set(cachedFrame.data);
          post(id, true, { page, pages: currentPages, image: reply.buffer, mono: wantMono, cached: true,
                           timing: renderTiming(tRender0, 0, 0, 0, true, null),
                           viewport: vpInfo ? vpInfo.viewport : null,
                           margins: vpInfo ? vpInfo.margins : null },
               [reply.buffer]);
          // §5: a hit must also extend the chain, or sequential reading only covers every other turn.
          schedulePrefetch(currentSpine, page, currentPages, wantMono, rk, builtFontStamp, bookGen);
          break;
        }

        tick('renderPage');
        COUNTERS.renders += 1;
        const tRenderStart = performance.now();
        const rc = renderPageEngine(page, wantMono);
        tock('renderPage');
        const renderMs = performance.now() - tRenderStart;
        const imgPerf = readImagePerf();
        if (rc !== 0) { post(id, false, { error: 'render failed' }); return; }
        // No plane copies: the compose runs inside the engine and reads the engine's own
        // planes, so copying 3 x 48 KB out of wasm here was pure waste.
        tick('compose');
        // compose through the SAME quantization the encoder uses for the chosen
        // mode: 1-bit → BW plane only (no AA greys), 2-bit → full 4-level
        const tCompose0 = performance.now();
        const img = wantMono ? composeMono() : composePage();
        const composeMs = performance.now() - tCompose0;
        tock('compose');
        frameCachePut(frameKey, img.data);      // copied: this buffer is transferred below
        const tx = img.data.buffer;
        COUNTERS.framesPosted += 1;
        // §2: user-visible work is finished — send it NOW. The prefetch is speculative and must never
        // delay the requested frame (it used to run between compose() and post()).
        const est = sectionEstimates[currentSpine] || { pages: currentPages, estimated: currentPages, complete: true };
        post(id, true, { page, pages: currentPages, image: tx, mono: wantMono,
                         // `pages` is what EXISTS (navigation clamps to it); `total` is what to display —
                         // a giant spine still building knows its estimate, not its final count.
                         total: est.complete ? currentPages : Math.max(est.estimated || 0, currentPages),
                         sectionComplete: !!est.complete,
                         timing: renderTiming(tRender0, buildMs, renderMs, composeMs, false, imgPerf),
                         viewport: vpInfo ? vpInfo.viewport : null,
                         margins: vpInfo ? vpInfo.margins : null }, [tx]);
        if (continuation) continueSection(continuation.spine, continuation.gen, BUILD_CHUNK);
        schedulePrefetch(currentSpine, page, currentPages, wantMono, rk, builtFontStamp, bookGen);
        break;
      }

      case 'cover': {
        // generate cover BMP in the engine and return raw BMP bytes
        const rc = api._ko_generate_cover(ev.data.kind || 0);
        if (rc !== 0) {
          const ep = api._ko_error();
          post(id, false, { error: 'cover gen: ' + (api.UTF8ToString(ep) || 'failed') });
          return;
        }
        const ptr = api._ko_cover_ptr();
        const size = api._ko_cover_size();
        const bytes = new Uint8Array(api.HEAPU8.buffer.slice(ptr, ptr + size));
        const tx = bytes.buffer;
        post(id, true, { cover: tx }, [tx]);
        break;
      }

      case 'convertFont': {
        if (foregroundExportRunning) { post(id, false, { error: 'font locked during export' }); break; }
        // TTF/OTF -> .epdfont, in this worker. This is the ONLY conversion path on the
        // hosted build (no backend there), and app.js prefers it locally too: the font
        // bytes never leave the tab and a full Hangul font lands in ~150-400 ms.
        // Parity with tools/ttf_to_epdfont_fast.py is byte-for-byte on every case
        // measured (scripts/verify/epdfont_parity.js).
        tick('convertFont');
        const conv = await getFontConverter();
        const res = conv.convert({
          fontBytes: new Uint8Array(ev.data.font),
          name: ev.data.name || 'custom',
          size: ev.data.size || 14,
          twoBit: ev.data.twoBit !== false,
          weight: ev.data.weight || 500,
          noHangul: !!ev.data.noHangul,
          extraIntervals: ev.data.extraIntervals || [],
          spacePx: ev.data.spacePx,
        });
        const buf = res.bytes.buffer;
        tock('convertFont');
        post(id, true, {
          epdfont: buf,
          meta: {
            glyphs: res.glyphCount, intervals: res.intervalCount, bitmapBytes: res.bitmapBytes,
            advanceY: res.advanceY, ascender: res.ascender, descender: res.descender,
            weightMode: res.weightMode, effectiveWeight: res.effectiveWeight,
            nativeWeight: res.nativeWeight, emboldenPx64: res.emboldenPx64,
            ftVersion: ftVersionString,
          },
        }, [buf]);
        break;
      }

      case 'loadFont': {
        if (foregroundExportRunning) { post(id, false, { error: 'font locked during export' }); break; }
        await stopWarmBeforeMutation();
        // ev.data.epdfont: ArrayBuffer, ev.data.name: string
        tick('loadFont');
        customFontBytes = new Uint8Array(ev.data.epdfont);
        customFontName = (ev.data.name || 'custom').replace(/[^\w-]/g, '') || 'custom';
        fontStamp++;
        clearFrameCache();    // §6: frames keyed by the old stamp can never hit again
        tick('applyFont');
        const ok = applyFont('custom');
        tock('applyFont');
        tock('loadFont');
        if (!ok) {
          const ep = api._ko_error();
          post(id, false, { error: 'epdfont load: ' + (api.UTF8ToString(ep) || 'failed') });
          return;
        }
        post(id, true, { font: 'custom', fontStamp });
        break;
      }

      case 'clearFont': {
        if (foregroundExportRunning) { post(id, false, { error: 'font locked during export' }); break; }
        await stopWarmBeforeMutation();
        customFontBytes = null;
        fontStamp++;
        clearFrameCache();    // §6: frames keyed by the old stamp can never hit again
        appliedFont = null;          // §1: face selection must be re-sent
        api._ko_clear_custom_font();
        currentSpec = Object.assign(currentSpec || defaultSpec(), { font: defaultSpec().font });
        post(id, true, { font: defaultSpec().font, fontStamp });
        break;
      }

      case 'warm': {
        // Background whole-book conversion (settings settled → pre-render the
        // book so the file is ready when the user hits export). Mirrors the
        // exportBook pipeline but WITHOUT transferring megabytes back to the
        // app: the finished container stays in the worker, and the app pulls
        // it only on download via 'fetchWarm'. warmToken lets a newer warm
        // supersede an in-flight one.
        const myTok = ev.data.token || 0;
        if (myTok < warmToken) { post(id, true, { warm: 'superseded' }); break; }
        warmToken = Math.max(warmToken, myTok);   // adopt: newer warms supersede
        if (warmRunning) { post(id, true, { warm: 'busy' }); break; }
        beginWarm();
        // The warm pass drives the engine through every spine; the JS tracker
        // (currentSpine) can't follow, so any render that interleaves between
        // the warm's spine yields must force a rebuild of its own spine.
        invalidateEngine();
        dropWarmResult();     // §3: never hold this warm plus a previous one
        try {
          tick('warm');
          // §3 of the 1.3 audit: the warm carries the spec it is producing, so it does not depend on
          // a preview render having already applied the same settings.
          if (ev.data.spec) await applySpecIfChanged(ev.data.spec);
          // §1 of the 1.4 audit: this local used to be named warmMode, shadowing the module-level
          // metadata variable — the assignment further down then threw "Assignment to constant
          // variable" AFTER the whole book was rendered, so the warm never reported ready.
          const selectedWarmMode = ev.data.mode === 0 ? 0 : 1;
          api._ko_export_set_mode(selectedWarmMode);
          // the tone depth must follow the MODE (a 1-bit page packs 2 tones); the warm previously
          // inherited whatever the spec said, so a 1-bit warm could pack 4-level pages into one plane
          const warmDepth = selectedWarmMode === 0 ? 2 : 4;
          api._ko_set_image_tone_depth(warmDepth);
          if (currentSpec) currentSpec.imageToneDepth = warmDepth;
          // No size preflight and no cap. The preflight paginated every spine to decide whether to
          // paginate every spine, so a book that passed it was laid out TWICE, and a book that failed
          // it was laid out once for nothing and then again at export time. Both were artefacts of
          // sharing this engine with the reader; with a dedicated export engine there is no
          // interactive work here to starve, so the honest thing is to convert the book the user
          // asked for.
          //
          // Cancellation is still cheap: a superseding warm bumps the token and the loop checks it at
          // every spine, and the app terminates this worker outright when the request itself changes.
          const res = await exportWholeBook({
            mode: selectedWarmMode,
            xtcz: !!ev.data.xtcz,
            cancelCheck: () => myTok < warmToken,   // a newer warm superseded us
          });
          if (myTok < warmToken) { post(id, true, { warm: 'superseded' }); break; }
          if (res.cancelled) { post(id, true, { warm: 'cancelled' }); break; }
          warmBytes = res.file;
          warmPages = res.pages;
          warmRaw = res.rawBytes || 0;
          warmMode = selectedWarmMode;      // module-level metadata
          warmXtcz = !!ev.data.xtcz;
          tock('warm');
          invalidateEngine();
          post(id, true, { warm: 'ready', pages: res.pages,
                           spineTimes: LAST_EXPORT.spines, preflight: LAST_EXPORT.preflight });
        } finally {
          invalidateSectionTracking();   // §1: also on a cancelled or superseded warm
          endWarm();
        }
        break;
      }

      case 'warmCancel': {
        // settings changed mid-warm → tell the in-flight warm to abort at the
        // next spine yield (it polls myTok < warmToken). No new warm starts;
        // the app will fire one again once the user settles.
        warmToken++;
        dropWarmResult();     // §3: a superseded/cancelled warm's megabytes must not linger
        post(id, true, { warmCancel: true });
        break;
      }

      case 'fetchWarm': {
        if (!warmBytes) { post(id, false, { error: 'no warm bytes' }); break; }
        const tx = takeTransferBuffer(warmBytes)   // §2: no full-file copy;
        const meta = { pages: warmPages, mode: warmMode, xtcz: warmXtcz, rawBytes: warmRaw };
        warmBytes = null;   // hand over once
        post(id, true, Object.assign({ file: tx }, meta), [tx]);
        break;
      }

      case 'warmState': {
        post(id, true, { has: !!warmBytes, pages: warmPages, mode: warmMode, xtcz: warmXtcz });
        break;
      }

// Call fn(ptr) with a NUL-terminated UTF-8 copy of `str` in wasm memory. Written out explicitly
// instead of relying on the JS glue to marshal a string for a char* argument: it is not obvious from
// the call site whether that conversion happens, and a silently-null path is exactly the kind of thing
// that would produce a container with missing chapter names and no error.
      case 'spineHrefs': {
        // On demand again: safe because ko_get_spine_href() copies the href into its own buffer instead of
        // pointing into a by-value temporary (see the note where the snapshot used to be).
        const start = Math.max(0, ev.data.start | 0);
        const count = Math.max(1, ev.data.count | 0);
        const end = Math.min(spineCount, start + count);
        const hrefs = [];
        for (let s = start; s < end; s++) {
          hrefs.push(api.UTF8ToString(api._ko_get_spine_href(s)));
        }
        post(id, true, { start, hrefs });
        break;
      }

      case 'timing': {
        post(id, true, { load: loadTiming, counters: COUNTERS });
        break;
      }

      case 'encodeSpine': {
        // ONE spine, laid out + rendered + ENCODED on this engine, returned as a single transferable
        // buffer. This is the unit of parallel work: rendering is ~85% of export time and it is
        // per-spine work, while the container is not. Page encoding is unchanged — the same writer
        // the serial path uses, on a spine-local basis.
        if (foregroundExportRunning) { post(id, false, { error: 'export already running' }); break; }
        foregroundExportRunning = true;
        try {
          await stopWarmBeforeMutation();
          if (ev.data.spec) await applySpecIfChanged(ev.data.spec);
          const m = ev.data.mode === 0 ? 0 : 1;
          api._ko_export_set_mode(m);
          api._ko_set_image_tone_depth(m === 0 ? 2 : 4);
          if (currentSpec) currentSpec.imageToneDepth = m === 0 ? 2 : 4;
          const spine = ev.data.spine | 0;
          invalidateSection();
          const n = api._ko_encode_spine(spine);
          if (n < 0) { post(id, false, { error: 'encode spine failed: ' + spine }); break; }
          const ptr = api._ko_spine_data_ptr();
          const size = api._ko_spine_data_size();
          const bytes = api.HEAPU8.slice(ptr, ptr + size);
          // Only the per-page LENGTHS cross; offsets are their prefix sum, derivable exactly.
          const lptr = api._ko_spine_page_lengths();
          const lengths = Array.from(new Uint32Array(api.HEAPU8.buffer, lptr, n));
          const tocN = api._ko_spine_toc_count();
          const toc = [];
          for (let i = 0; i < tocN; i++) {
            toc.push({ tocIndex: api._ko_spine_toc_index(i),
                       localPage: api._ko_spine_toc_local_page(i),
                       title: api.UTF8ToString(api._ko_spine_toc_title(i)) });
          }
          post(id, true, {
            spine, pageCount: n, bytes: bytes.buffer, lengths, toc,
            fallbackName: api.UTF8ToString(api._ko_spine_fallback_name()),
          }, [bytes.buffer]);
        } finally {
          foregroundExportRunning = false;
        }
        break;
      }

      case 'planPrefix': {
        // Prefix-only assembly: the records never enter an engine. The container's fixed region is a
        // function of the page SIZES and the chapters, so this returns ~10 KB of header/metadata/
        // chapter-table/index and the caller composes [prefix][records…] in the browser. Uncompressed
        // XTC/XTCH only — XTCZ needs the byte stream, so it uses assembleSpines.
        const mode = ev.data.mode === 0 ? 0 : 1;
        if (api._ko_plan_begin(mode) < 0) { post(id, false, { error: 'plan begin failed' }); break; }
        let base = 0;
        let recordBytes = 0;
        let bad = null;
        for (const sp of (ev.data.spines || [])) {
          const pages = sp.pageCount | 0;
          if (pages <= 0) continue;                       // matches the serial path's `if (added > 0)`
          const lengths = Uint32Array.from(sp.lengths || []);
          if (lengths.length !== pages) { bad = 'spine ' + sp.spine + ': ' + lengths.length + ' lengths for ' + pages + ' pages'; break; }
          const lptr = api._malloc(pages * 4);
          try {
            new Uint32Array(api.HEAPU8.buffer, lptr, pages).set(lengths);
            if (api._ko_plan_add_spine(lptr, pages) < 0) { bad = 'plan add spine failed'; break; }
          } finally {
            api._free(lptr);
          }
          for (const t of (sp.toc || [])) {
            withCString(t.title, (tp) => api._ko_plan_add_toc(base, tp, t.localPage | 0));
          }
          withCString(sp.fallbackName, (fp) => api._ko_plan_add_fallback(base, fp, pages));
          for (let i = 0; i < pages; i++) recordBytes += lengths[i];
          base += pages;
        }
        if (bad) { post(id, false, { error: bad }); break; }
        const total = api._ko_plan_finish();
        if (total < 0) { post(id, false, { error: 'plan finish failed' }); break; }
        const pptr = api._ko_plan_prefix_ptr();
        const psize = api._ko_plan_prefix_size();
        const prefix = api.HEAPU8.slice(pptr, pptr + psize);
        post(id, true, { pages: total, spinePages: base, prefix: prefix.buffer,
                         prefixBytes: psize, recordBytes, rawBytes: psize + recordBytes },
             [prefix.buffer]);
        break;
      }

      case 'assembleSpines': {
        // ONE assembler writes the container. The records arrive already encoded; this only appends
        // them in the order the caller sent (spine order) and builds the chapter table with the same
        // shared builder the serial path uses. Completion order must never reach this code, so the
        // caller is responsible for sending spines in index order.
        const mode = ev.data.mode === 0 ? 0 : 1;
        if (api._ko_assemble_begin(mode) < 0) { post(id, false, { error: 'assemble begin failed' }); break; }
        let base = 0;
        let raw = 0;
        let bad = null;
        for (const sp of (ev.data.spines || [])) {
          const pages = sp.pageCount | 0;
          if (pages <= 0) continue;                     // matches the serial path's `if (added > 0)`
          const lengths = sp.lengths;
          const bytes = new Uint8Array(sp.bytes);
          const offs = new Uint32Array(pages);
          let acc = 0;
          for (let i = 0; i < pages; i++) { offs[i] = acc; acc += lengths[i]; }
          if (acc !== bytes.length) { bad = 'spine ' + sp.spine + ': lengths sum ' + acc + ' != ' + bytes.length + ' bytes'; break; }
          const bptr = api._malloc(bytes.length);
          const optr = api._malloc(pages * 4);
          const lptr = api._malloc(pages * 4);
          try {
            api.HEAPU8.set(bytes, bptr);
            new Uint32Array(api.HEAPU8.buffer, optr, pages).set(offs);
            new Uint32Array(api.HEAPU8.buffer, lptr, pages).set(lengths);
            if (api._ko_assemble_add_spine(bptr, bytes.length, pages, optr, lptr) < 0) {
              bad = 'assemble add spine failed for spine ' + sp.spine; break;
            }
          } finally {
            api._free(bptr); api._free(optr); api._free(lptr);
          }
          for (const t of (sp.toc || [])) {
            const r = withCString(t.title, (tp) => api._ko_assemble_add_toc(base, tp, t.localPage | 0));
            void r;
          }
          withCString(sp.fallbackName, (fp) => api._ko_assemble_add_fallback(base, fp, pages));
          base += pages;
          raw += bytes.length;
        }
        if (bad) { post(id, false, { error: bad }); break; }
        const total = api._ko_assemble_finish();
        if (total < 0) { post(id, false, { error: 'assemble finish failed' }); break; }
        // rawBytes is the UNCOMPRESSED container — header, metadata, chapters, index and records. It
        // used to be the sum of the page records, which made the UI divide by a number that excluded
        // everything but the records. recordBytes keeps the old figure as an assembly diagnostic.
        const rawBytes = api._ko_xtch_size();
        if (ev.data.xtcz) api._ko_xtcz_wrap();
        const p2 = api._ko_xtch_ptr();
        const sz = api._ko_xtch_size();
        const out = api.HEAPU8.slice(p2, p2 + sz);
        post(id, true, { pages: total, spinePages: base, recordBytes: raw,
                         xtcz: !!ev.data.xtcz, rawBytes,
                         bytes: out.buffer }, [out.buffer]);
        break;
      }

      case 'exportBook': {
        // whole-book export with the current spec; 1-bit XTC or 2-bit XTCH per
        // mode (xtcz=true wraps in XTZ4/LZ4); progress posts (no op id)
        // A background warm may be driving the engine: it shares the C export
        // buffer, so supersede it and wait for it to stop (it polls the token
        // between spines and aborts within a few yields).
        if (foregroundExportRunning) {
          post(id, false, { error: 'export already running' });
          break;
        }
        // §1: from here to the finally, the engine state is frozen: any mutating command that arrives
        // in a yield window is rejected rather than silently changing what the file contains.
        foregroundExportRunning = true;
        // §1 of the 1.5 audit: the try must begin HERE. It used to begin after the setup, so a throw
        // from stopWarmBeforeMutation / applySpecIfChanged / the export-mode setup left the lock set
        // forever — every later mutation then rejected for the life of the worker.
        let res;
        try {
        // §2: same fail-closed wait as any other mutation (it also drops the superseded warm bytes)
        await stopWarmBeforeMutation();
        // The tone depth must follow the MODE, not whatever spec happens to be
        // applied: a 1-bit page has to be dithered straight to 2 tones, and if the
        // spec still says 4 the writer packs a 4-level page into one plane (the
        // host CLI has always done this; the worker relied on the caller passing
        // imageToneDepth, which any new export path could forget).
        // §3 of the 1.3 audit: the snapshot is applied AFTER the lock is held, so the settings the
        // file is built from are exactly the settings the caller sent with this one message.
        if (ev.data.spec) await applySpecIfChanged(ev.data.spec);
        const exportMode = ev.data.mode === 0 ? 0 : 1;
        api._ko_export_set_mode(exportMode);
        const exportDepth = exportMode === 0 ? 2 : 4;
        api._ko_set_image_tone_depth(exportDepth);
        if (currentSpec) currentSpec.imageToneDepth = exportDepth;
        const opts = { xtcz: !!ev.data.xtcz };
          // exportWholeBook owns its own abort cleanup on every abnormal exit (cancel, spine
          // failure, finish failure), so there is no catch here: one owner for cleanup.
          invalidateSection();
          res = await exportWholeBook(opts, (spine, ofSpines, pages) => {
            self.postMessage({ progress: true, spine, ofSpines, pages });
          });
        // the export loop built+rendered every spine through the engine, so
        // per-spine engine state is undefined afterwards — force a rebuild on
        // the next engine render (keeps page flips after export safe)
        } finally {
          foregroundExportRunning = false;
        }
        invalidateEngine();
        // hand the finished bytes to the app as a transferable for download
        const tx = takeTransferBuffer(res.file)     // §2: no full-file copy;
        post(id, true, { file: tx, mode: ev.data.mode === 0 ? 0 : 1,
                         pages: res.pages, spines: res.spines,
                         xtcz: res.xtcz, rawBytes: res.rawBytes,
                         // diagnostic: per-spine ms and the preflight cost, if any. Storing these
                         // in the worker alone was useless — nothing could ask for them.
                         spineTimes: LAST_EXPORT.spines, preflight: LAST_EXPORT.preflight }, [tx]);
        break;
      }

      case 'pageCount': {
        post(id, true, { pages: currentPages, spine: currentSpine });
        break;
      }

      case 'stats': {
        post(id, true, {
          lastExport: LAST_EXPORT,
          times: cmdTimes,
          counters: COUNTERS,
          frameCache: { entries: frameCache.size, bytes: frameCacheBytes, budget: FRAME_CACHE_BUDGET },
          heapBytes: api ? api.HEAPU8.buffer.byteLength : 0,   // wasm linear memory high-water mark
          storageBytes: api ? api._ko_storage_bytes() : 0,     // what HalStorage is actually holding
          engine: { spine: currentSpine, pages: currentPages, builtKey, fontStamp },
          keys: { layout: currentSpec ? layoutKey(currentSpec) : null,
                  render: currentSpec ? renderKey(currentSpec) : null },
          warmRunning,
        });
        break;
      }

      default:
        post(id, false, { error: 'unknown cmd ' + cmd });
    }
  } catch (e) {
    // A throw here usually means the wasm runtime aborted (OOM / bad_alloc
    // under -fno-exceptions). The engine is poisoned after an abort — flag
    // fatal so the app respawns the worker instead of retrying a dead engine.
    const msg = String(e && e.message || e);
    const fatal = /abort|runtime|out of memory|allocation/i.test(msg);
    try { post(id, false, { error: msg, fatal }); } catch (_) {}
    if (fatal) {
      // give the reply a moment to flush, then die loudly (app respawns)
      setTimeout(() => { throw new Error('engine aborted: ' + msg); }, 0);
    }
  }
};
