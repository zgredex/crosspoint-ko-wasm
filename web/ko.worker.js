// per-command wall-clock timing (ms) — n = cumulative invocations
let cmdTimes = {};
function tick(cmd) {
  if (!cmdTimes[cmd]) cmdTimes[cmd] = { n: 0 };
  cmdTimes[cmd].t0 = performance.now();
}
function tock(cmd) {
  const e = cmdTimes[cmd];
  if (e) { e.ms = performance.now() - e.t0; e.n += 1; }
}

