const DEFAULT_FACE = 'kopub';

// Fetch the EPD2 bytes for a face. No engine involved, so this can run while the module is still
// being fetched and compiled — that parallelism is the point.
//
// Retried, because an externalized face is on the BOOT-CRITICAL path: the default reader face is a
// separate request from the module now, so the chance of at least one critical fetch failing is
// strictly higher than when the font travelled inside the module, and the failure mode is a reader
// with no font at all. Three attempts with backoff, and `cache: 'reload'` on the retries so a
// poisoned or half-written cache entry cannot make every attempt fail the same way. A hard failure
// still throws — a wrong or missing face must never be rendered around.
async function fetchFaceBytes(name) {
  const url = asset(FACE_ASSETS[name]);
  let lastErr = null;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const r = await fetch(url, attempt === 0 ? undefined : { cache: 'reload' });
      if (!r.ok) throw new Error(`face ${name}: HTTP ${r.status} for ${FACE_ASSETS[name]}`);
      return { name, bytes: new Uint8Array(await r.arrayBuffer()) };
    } catch (e) {
      lastErr = e;
      if (attempt < 2) await new Promise((res) => setTimeout(res, 250 * (attempt + 1)));
    }
  }
  throw lastErr;
}

// name -> Promise<boolean>, memoised so a face is fetched and registered at most once even if several
// commands ask for it while the download is still in flight.
const facePromises = new Map();

// Bring a face into the engine on demand. Resolves true when it is available (embedded, or fetched
// and registered), and rejects only if the blob could not be fetched or was rejected by the loader —
// callers must not silently render with a missing face.
function ensureFace(name) {
  if (!name) return Promise.resolve(true);
  if (embeddedFaces().includes(name)) return Promise.resolve(true);
  if (api && api._ko_has_font(FACE_IDS[name])) return Promise.resolve(true);
  if (!facePromises.has(name)) {
    facePromises.set(name, (async () => {
      const fetched = await fetchFaceBytes(name);
      registerFaces([fetched]);
      return true;
    })());
    // a failed load must not poison the cache — the next attempt should retry
    facePromises.get(name).catch(() => facePromises.delete(name));
  }
  return facePromises.get(name);
}

// Copy each fetched blob into the module's heap ONCE and register it. The pointer is deliberately
// never freed: the engine's EpdFontData points straight into this allocation for the lifetime of the
// engine (see src/external_font_loader.h — the loader copies today, so freeing it would only be
// wrong once that becomes a zero-copy view; either way, ownership stays here).
const facePtrs = [];
function registerFaces(fetched) {
  const results = [];
  for (const { name, bytes } of fetched) {
    const ptr = api._malloc(bytes.length);
    if (!ptr) throw new Error(`face ${name}: malloc(${bytes.length}) failed`);
    api.HEAPU8.set(bytes, ptr);
    const rc = api._ko_load_external_builtin_font(FACE_IDS[name], ptr, bytes.length);
    if (rc !== 0) {
      api._free(ptr);
      throw new Error(`face ${name}: loader rejected the blob (rc=${rc}) ${api.UTF8ToString(api._ko_error())}`);
    }
    facePtrs.push(ptr);
    results.push({ name, bytes: bytes.length });
  }
  return results;
}

async function init() {
  // Emscripten MODULARIZE: ko_xtch_wasm.js defines createKoEngine in scope.
  const factory = self.createKoEngine;
  BOOT.glueReady = performance.now();
  BOOT.factoryStart = performance.now();
  // Start the default face's fetch BEFORE awaiting the module: two independent downloads, and the
  // point is that they overlap. Faces other than the default are left alone — they load on selection.
  const eagerFaces = embeddedFaces().includes(DEFAULT_FACE) ? [] : [DEFAULT_FACE];
  const facesPromise = Promise.all(eagerFaces.map(fetchFaceBytes))
    .catch((e) => { BOOT.faceError = String(e); return []; });
  // Cache-bust the engine binaries: the emscripten glue fetches the .wasm with no version
  // query, so without this the edge serves a previously cached engine indefinitely and no
  // engine change can ever reach a returning browser.
  Module = await factory({ locateFile: (path) => asset(path) });
  api = Module;
  BOOT.wasmReady = performance.now();
  // deterministic viewport: engine computes from margins; init with full logical
  api._ko_init(464, 764); // will be fixed up by ko_set_margins on first spec
  // Register external faces AFTER ko_init, not before: the loader needs the renderer that ko_init
  // creates (`ko_load_external_builtin_font` → "engine not initialised" otherwise) and
  // `ko_has_font` reads the renderer's registry. The parallel part is the FETCH above, which is the
  // part that costs network time; registration is a memcpy.
  const fetched = await facesPromise;
  if (fetched.length) {
    BOOT.facesRegistered = registerFaces(fetched);
    BOOT.facesBytes = BOOT.facesRegistered.reduce((n, f) => n + f.bytes, 0);
  }
  // A face that is neither compiled in nor fetched would render as blank pages, and nothing else in
  // the pipeline would say why. Only the DEFAULT face is a boot requirement: it is needed for the
  // first render. Every other face is fetched on demand by ensureFace(), so its absence here is the
  // expected state, not a degradation — reporting it as one would train people to ignore the message.
  if (!api._ko_has_font(FACE_IDS[DEFAULT_FACE])) {
    throw new Error(`reader face missing: ${DEFAULT_FACE} is neither embedded nor loaded `
                    + `(embedded: ${embeddedFaces().join(', ') || 'none'})`);
  }
  // Faces still absent because they are lazy. Recorded so `bootstats` can state the configuration
  // rather than leave it to be inferred from which assets happen to be on the server.
  BOOT.lazyFaces = FACE_NAMES.filter((f) => !api._ko_has_font(FACE_IDS[f]));
  BOOT.engineReady = performance.now();
  BOOT.phases = {
    glue: +(BOOT.glueReady - BOOT.workerStart).toFixed(1),
    factory: +(BOOT.wasmReady - BOOT.factoryStart).toFixed(1),
    init: +(BOOT.engineReady - BOOT.wasmReady).toFixed(1),
    total: +(BOOT.engineReady - BOOT.workerStart).toFixed(1),
  };
  // Wall clock at "engine ready", so the PAGE can express this relative to its own navigationStart
  // without the two contexts needing a shared timer (a worker's performance.now() has its own time
  // origin, so the phase numbers above are not comparable with the page's timeline on their own).
  BOOT.engineReadyWall = Date.now();
  self.__koBoot = BOOT;
  return true;
}

// Engine build-state invalidation. currentSpine/currentPages/builtKey describe what the ENGINE has
// built. Composed frames stay valid across a warm — a frame is a pure function of (book generation,
// spine, page, mode, render key, font stamp) — so the frame cache is NOT cleared here; only the
// tracking state is, and clearing on a load is explicit.
//
// §1 of the 1.1 audit: _ko_export_spine() internally calls g_driver->buildSection(spine, g_spec), so
// it changes the real C++ EngineDriver::section_ on every spine. Once preview renders may interleave
// with the warm, JS claiming "spine N is built" is a lie as soon as one export spine runs: the next
// uncached page of spine N would be rendered from whatever section_ the export last built. Section
// tracking therefore dies after EVERY export spine; the font cache only dies on a wholesale reset.
function invalidateSectionTracking() {
  currentSpine = -1;
  currentPages = 0;
  builtKey = null;
}
function invalidateEngine() {
  invalidateSectionTracking();
  appliedFont = null;          // the warm walked whole spines; re-send the face on the next spec
}

// Export the whole loaded book with the current spec, spine by spine (progress
// callback), returning the finished container bytes for download.
// opts.xtcz=true wraps the container in XTZ4 (LZ4) before copying out; the
// pre-wrap container size is reported as rawBytes (no JS-side unwrap needed).
// opts.cancelCheck() is polled between spines — returning true aborts early so
// a superseded background warm stops burning CPU (the half-built container is
// discarded; the next export begin() resets it).
async function exportWholeBook(opts, onProgress) {
  const xtcz = !!(opts && opts.xtcz);
  const cancelCheck = (opts && opts.cancelCheck) || null;
  tick('exportBegin');
  const spines = api._ko_export_begin();
  tock('exportBegin');
  if (spines < 0) throw new Error('export_begin failed');
  let total = 0;
  // Per-spine timing. Export is one engine doing every spine in order, so the only way to know
  // whether a spine pool is worth its complexity is to see the distribution: if 60 spines all cost
  // the same, N workers scale; if two spines are 80% of the work, they do not.
  const spineTimes = [];
  for (let s = 0; s < spines; s++) {
    tick('exportSpine');
    const tSpine = performance.now();
    const n = api._ko_export_spine(s);
    spineTimes.push({ spine: s, pages: n, ms: +(performance.now() - tSpine).toFixed(1) });
    tock('exportSpine');
    if (n < 0) {
      // abnormal exit: release the pages accumulated so far, then propagate
      api._ko_export_abort();
      invalidateSectionTracking();
      COUNTERS.aborts += 1;
      throw new Error('export spine ' + s + ' failed');
    }
    total += n;
    // §1: _ko_export_spine() just rebuilt the C++ section_ for THIS spine. Never let JS claim an
    // interactive spine is still built across this point.
    invalidateSectionTracking();
    if (onProgress) onProgress(s + 1, spines, total);
    // §4: yield after EVERY spine (measured: yielding every 4th let a page turn queue behind ~150 ms
    // of export work).
    COUNTERS.warmYields += 1;
    await yieldToLoop();
    if (cancelCheck && cancelCheck()) return cancelCurrentExport(total);
  }
  tick('exportFinish');
  const pages = api._ko_export_finish();
  tock('exportFinish');
  if (pages < 0) {
    api._ko_export_abort();
    invalidateSectionTracking();
    COUNTERS.aborts += 1;
    throw new Error('export_finish failed');
  }
  const rawBytes = api._ko_xtch_size();   // pre-wrap container size
  if (xtcz) {
    tick('xtczWrap');
    api._ko_xtcz_wrap();          // g_xtchOut → XTZ4 container in place
    tock('xtczWrap');
  }
  const ptr = api._ko_xtch_ptr();
  const size = api._ko_xtch_size();
  if (!ptr || size <= 0) {
    api._ko_export_abort();
    invalidateSectionTracking();
    COUNTERS.aborts += 1;
    throw new Error('export produced no bytes');
  }
  const out = new Uint8Array(api.HEAPU8.buffer.slice(ptr, ptr + size));
  api._ko_xtch_release();
  LAST_EXPORT.spines = spineTimes;
  LAST_EXPORT.preflight = preflightTimes;
  // Reported here as well as returned, because the *warm* path builds the container too — and the
  // warm is the common case in the app, so a report that only rides the explicit-export response is
  // invisible exactly when someone is looking at the conversion they just waited for.
  if (spineTimes.length && typeof console !== 'undefined' && console.log) {
    const ms = spineTimes.map((x) => x.ms).sort((a, b) => a - b);
    const sum = ms.reduce((a, b) => a + b, 0);
    const heaviest = Math.max(...ms);
    const speedup = (n) => sum / Math.max(sum / n, heaviest);
    console.log(`[export] ${spines} spines, ${pages} pages, ${sum.toFixed(0)} ms of spine work `
                + `(min ${ms[0].toFixed(1)} p50 ${ms[Math.floor(ms.length * 0.5)].toFixed(1)} `
                + `p90 ${ms[Math.floor(ms.length * 0.9)].toFixed(1)} max ${heaviest.toFixed(1)}) `
                + `ceiling ${speedup(4).toFixed(2)}x@4w ${speedup(8).toFixed(2)}x@8w`
                + (preflightTimes ? ` | preflight ${preflightTimes.ms} ms for ${preflightTimes.pages} pages` : ''));
  }
  return { file: out, pages, bytes: out.byteLength, spines, xtcz, rawBytes: rawBytes || 0 };
}

