// Copy a 48000-byte plane from wasm heap into a JS Uint8Array.
function copyPlane(kind) {
  const ptr = api._ko_plane_ptr(kind);
  const size = api._ko_plane_size(kind);
  if (!ptr || size <= 0) return null;
  return new Uint8Array(api.HEAPU8.buffer.slice(ptr, ptr + size));
}

// Compose the 3 physical (800x480) planes into a logical portrait 480x800
// grayscale image per the device decode contract:
//   value = !ink?white : lsb?dark-grey : msb?light-grey : black
//   logical(x,y) ← physical(phyX=y, phyY=479-x)
const GRAY = [255, 128, 205, 0]; // white, dark-grey, light-grey, black


// 1-bit (XTC / XTG) preview: the file stores ONLY the BW plane — no AA greys.
// Bit 0 = black on the device; this is byte-exactly what addMonoPage() packs.
// The pixels are composed inside the engine now: ko_compose_rgba() fills an engine-owned
// 480x800 RGBA buffer and we wrap it as a ZERO-COPY view. No JS pixel loop exists.
// The buffer can move if wasm memory grows, so the pointer is fetched AFTER composing and
// the view is rebuilt every call. putImageData reads it synchronously, so the view stays valid.
// tick/tock are the worker's existing stage timers; used defensively so this stays valid if
// they are not in scope here.
function _stage(name, fn) {
  const has = typeof tick === 'function' && typeof tock === 'function';
  if (has) tick(name);
  try { return fn(); } finally { if (has) tock(name); }
}

// A view over wasm memory CANNOT be transferred through postMessage - the browser throws
// 'cannot transfer WebAssembly ArrayBuffer', because wasm memory is non-detachable by spec.
// So the frame is copied out into a normal ArrayBuffer here: one native typed-array copy
// (~1.5 MB), not per-pixel work. The engine-side compose and its single 32-bit store per
// pixel are unaffected.
function _frameFromEngine() {
  const src = new Uint8ClampedArray(api.HEAPU8.buffer, api._ko_rgba_ptr(), 480 * 800 * 4);
  const img = new ImageData(480, 800);
  img.data.set(src);
  return img;
}

// 1-bit callers (XTC preview/export) read only the BW plane, so the engine can skip both gray passes.
// Falls back to the plain entry point if this module predates ko_render_page_mode.
function renderPageEngine(page, mono) {
  if (api._ko_render_page_mode) return api._ko_render_page_mode(page, mono ? 1 : 0);
  return api._ko_render_page(page);
}

function composeMono() {
  _stage('compose.mono', () => {
    if (api._ko_compose_rgba(1) !== 0) throw new Error('engine compose failed (mono)');
  });
  return _stage('compose.view', _frameFromEngine);
}

function composePage() {
  _stage('compose.page', () => {
    if (api._ko_compose_rgba(0) !== 0) throw new Error('engine compose failed');
  });
  return _stage('compose.view', _frameFromEngine);
}

// §2 of the 1.5 audit: the size cap used to be checked AFTER _ko_export_spine() had rendered and
// stored a whole spine, so one giant XHTML spine could allocate hundreds of MB before the check ran —
// and Emscripten never returns linear memory, so the high-water mark stayed grown even after the abort.
// Decide from pagination alone, before any encoded page exists. Small books get paginated twice; that
// is deliberate, and measure before caching page counts by layout key.

// §2 + §5 of the 1.1 audit: speculation must never sit in front of the requested frame, and a
// cache HIT must schedule a prefetch too — otherwise a sequential read alternates miss/hit and only
// every other turn is covered.
//
// The reply is posted first; this runs as its own macrotask, so the extra render cannot delay the
// frame the user is waiting for. Every guard is re-checked when the task actually runs: if a warm
// started, the book changed, the spine/page state moved on, or the render key or font stamp changed,
// a frame rendered now would belong to different state — so it is dropped instead of cached.
// §2 of the 1.4 audit: an export result is built with an exact ArrayBuffer.slice(), so its buffer is
// already exactly the payload and can be transferred as-is. Re-slicing it before post() copied the
// whole output a second time — harmless at 674 KB, hundreds of MB on a large export. The fallback only
// exists for a future caller that hands over a subview.
function takeTransferBuffer(u8) {
  if (u8.byteOffset === 0 && u8.byteLength === u8.buffer.byteLength) return u8.buffer;
  return u8.slice().buffer;
}

function schedulePrefetch(spine, page, pages, mono, rk, fStamp, gen) {
  setTimeout(() => {
    if (warmRunning) return;                       // the engine is walking spines
    if (gen !== bookGen) return;                   // different book
    if (spine !== currentSpine || pages !== currentPages) return;
    if (fStamp !== builtFontStamp) return;
    if (rk !== renderKey(currentSpec || {})) return;
    const next = page + 1;
    if (next >= pages) return;
    const nk = gen + ':' + spine + ':' + next + ':' + (mono ? 1 : 0) + ':' + rk + ':' + fStamp;
    if (frameCache.has(nk)) return;
    // Always preceded by a real render of the requested page, so the engine's planes can never be
    // composed as the wrong page here.
    if (renderPageEngine(next, mono) !== 0) return;
    const nextImg = mono ? composeMono() : composePage();
    frameCachePut(nk, nextImg.data, true);         // never transferred → the cache takes ownership
    COUNTERS.prefetches += 1;
  }, 0);
}

